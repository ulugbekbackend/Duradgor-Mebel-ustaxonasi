const Ctx = createContext(null);

export function I18nProvider({ children }) {
  const [lang, setLangState] = useState(() => localStorage.getItem("dg_lang") || "uz");

  useEffect(() => {
    localStorage.setItem("dg_lang", lang);
    document.documentElement.lang = lang;
  }, [lang]);

  const setLang = useCallback((l) => setLangState(l), []);
  const t = useCallback((k) => DICT[lang][k] ?? DICT.uz[k] ?? k, [lang]);
  const L = useCallback((lt) => (lt ? lt[lang] ?? lt.uz : ""), [lang]);

  const value = useMemo(() => ({ lang, setLang, t, L }), [lang, setLang, t, L]);
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export function useI18n() {
  const ctx = useContext(Ctx);
  if (!ctx) throw new Error("useI18n I18nProvider ichida chaqirilishi kerak");
  return ctx;
}
